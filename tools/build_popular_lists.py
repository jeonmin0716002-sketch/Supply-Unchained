"""Fetch most-downloaded package names per ecosystem into ecosystems/data/popular/<id>.txt.

Usage:
    uv run python tools/build_popular_lists.py            # all ecosystems
    uv run python tools/build_popular_lists.py --only pip  # one ecosystem

Each ecosystem has its own fetch function. A failing source prints an error and is
skipped; its existing list file is left untouched (an empty result never overwrites).
"""

from __future__ import annotations

import argparse
import re
import sys
import time
from datetime import date
from pathlib import Path

import httpx

OUT_DIR = Path(__file__).resolve().parents[1] / "ecosystems" / "data" / "popular"
TARGET = 500
USER_AGENT = "supply-unchained-scanner"
DELAY = 1.0  # seconds between paged requests
TIMEOUT = 30.0


class SourceError(RuntimeError):
    pass


def _get_json(client: httpx.Client, url: str, params: dict | None = None) -> object:
    try:
        r = client.get(url, params=params, timeout=TIMEOUT)
        r.raise_for_status()
        return r.json()
    except (httpx.HTTPError, ValueError) as exc:
        raise SourceError(f"GET {url} failed: {exc}") from exc


def _client() -> httpx.Client:
    return httpx.Client(headers={"User-Agent": USER_AGENT}, follow_redirects=True)


def fetch_pip(client: httpx.Client) -> tuple[str, list[str]]:
    url = "https://hugovk.github.io/top-pypi-packages/top-pypi-packages.min.json"
    data = _get_json(client, url)
    if not isinstance(data, dict) or not isinstance(data.get("rows"), list):
        raise SourceError(f"unexpected shape from {url}")
    # rows are already sorted by download_count descending
    names = [row["project"] for row in data["rows"] if isinstance(row, dict) and row.get("project")]
    return url, names[:TARGET]


def fetch_npm(client: httpx.Client) -> tuple[str, list[str]]:
    url = "https://raw.githubusercontent.com/wooorm/npm-high-impact/main/lib/top.js"
    try:
        r = client.get(url, timeout=TIMEOUT)
        r.raise_for_status()
    except httpx.HTTPError as exc:
        raise SourceError(f"GET {url} failed: {exc}") from exc
    # the file is a JS array literal of single-quoted names, in rank order
    names = re.findall(r"'([^']+)'", r.text)
    return url, list(dict.fromkeys(names))[:TARGET]


def fetch_cargo(client: httpx.Client) -> tuple[str, list[str]]:
    url = "https://crates.io/api/v1/crates"
    names: list[str] = []
    for page in range(1, TARGET // 100 + 1):
        data = _get_json(client, url, {"sort": "downloads", "per_page": 100, "page": page})
        crates = data.get("crates") if isinstance(data, dict) else None
        if not crates:
            break
        names.extend(c["name"] for c in crates if isinstance(c, dict) and c.get("name"))
        time.sleep(DELAY)
    if not names:
        raise SourceError(f"no crates returned from {url}")
    return f"{url}?sort=downloads", list(dict.fromkeys(names))[:TARGET]


FETCHERS = {
    "pip": fetch_pip,
    "npm": fetch_npm,
    "cargo": fetch_cargo,
}


def write_list(eco: str, source: str, names: list[str]) -> Path:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / f"{eco}.txt"
    header = [
        f"# Source: {source}",
        f"# Fetched: {date.today().isoformat()}",
        "# Most-downloaded names first. Generated by tools/build_popular_lists.py.",
    ]
    path.write_text("\n".join(header + names) + "\n", encoding="utf-8")
    return path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--only", choices=sorted(FETCHERS), help="build a single ecosystem")
    args = parser.parse_args(argv)

    targets = [args.only] if args.only else list(FETCHERS)
    failed: list[str] = []
    with _client() as client:
        for eco in targets:
            try:
                source, names = FETCHERS[eco](client)
                if not names:
                    raise SourceError("source returned zero names")
                path = write_list(eco, source, names)
                print(f"{eco}: {len(names)} names -> {path}")
            except SourceError as exc:
                failed.append(eco)
                print(f"{eco}: FAILED - {exc} (existing file left unchanged)", file=sys.stderr)
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
